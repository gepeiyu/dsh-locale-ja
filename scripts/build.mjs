import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { checkedDictionaries, project } from './locales.mjs';

const dictionaries = await checkedDictionaries();
const namespaces = Object.keys(dictionaries);
const manifest = JSON.parse(await readFile(new URL('package.json', project), 'utf8'));
await mkdir(new URL('lib/', project), { recursive: true });

// Keep the authored ESM entry usable in Node and other bundlers.
await writeFile(new URL('src/locales/index.js', project), namespaces.map((ns, i) =>
  `import dictionary${i} from './ja/${ns}.json' with { type: 'json' };`).join('\n') +
  '\n\nexport const dictionaries = Object.freeze({\n' + namespaces.map((ns, i) =>
    `  ${JSON.stringify(ns)}: Object.freeze(dictionary${i}),`).join('\n') + '\n});\n');

const source = await readFile(new URL('src/client/index.js', project), 'utf8');
const importLine = "import { dictionaries } from '../locales/index.js';";
if (!source.startsWith(importLine)) throw new Error('Unexpected client entry import');
const body = source.slice(importLine.length).replace(/^export /gm, '');
// Harness serves ./client as a classic script and materializes its CJS factory.
// No external modules or runtime dependencies are needed for a language pack.
const bundle = `// Generated by scripts/build.mjs.\n` +
  `window.__ModuleLoader__.load({ id: ${JSON.stringify(manifest.name)}, factory: (require) => {\n` +
  `const dictionaries = Object.freeze(${JSON.stringify(dictionaries)});\n` +
  `for (const dictionary of Object.values(dictionaries)) Object.freeze(dictionary);\n` +
  body + '\nreturn { name, inject, language, apply };\n} });\n';
await writeFile(new URL('lib/client.js', project), bundle);
await writeFile(new URL('lib/index.js', project), await readFile(new URL('src/index.js', project)));
await writeFile(new URL('lib/locales.js', project), "export { dictionaries } from '../src/locales/index.js';\n");
console.log(`Built dsh-locale-ja/client with ${namespaces.length} Japanese dictionaries.`);
